/// Compress `data` with an external tool, returning its size. `None` if the
/// tool is absent — the page then says so rather than inventing a number.
fn compressed_len(tool: &str, args: &[&str], data: &[u8]) -> Option<usize> {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let mut child = Command::new(tool)
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .ok()?;
    let mut stdin = child.stdin.take()?;
    let owned = data.to_vec();
    let writer = std::thread::spawn(move || stdin.write_all(&owned));
    let out = child.wait_with_output().ok()?;
    writer.join().ok()?.ok()?;
    out.status.success().then_some(out.stdout.len())
}

/// A stand-in for column data: incompressible, so the registry's share of the
/// archive is exactly what the measurement isolates.
fn pseudo_payload(n: usize, seed: u64) -> Vec<u8> {
    let mut s = seed | 1;
    (0..n)
        .map(|_| {
            s ^= s << 13;
            s ^= s >> 7;
            s ^= s << 17;
            (s >> 24) as u8
        })
        .collect()
}

fn page_composition() -> String {
    let mut s = String::new();
    writeln!(s, "# Composing registries\n").unwrap();
    writeln!(
        s,
        "A pipeline that reads tables from two domains needs units from two \
         registries. This page is generated by actually composing them.\n\n\
         Register entries: {} (no composition story), {} (combining across \
         registries is silently wrong), {} (a multi-registry table has no \
         describable provenance).\n",
        amb("AMB-058"), amb("AMB-059"), amb("AMB-060")
    )
    .unwrap();

    // ---- 1. the hazard --------------------------------------------------
    writeln!(s, "## Why this cannot be left to the consumer\n").unwrap();
    writeln!(
        s,
        "Two registries, each valid on its own, each defining `bbl`. Oil means \
         42 US gallons; the water side means 31.5. Canonical form is \
         registry-**relative**, so both canonicalize to the same string:\n"
    )
    .unwrap();
    let oil = Registry::from_toml(&oil_source().toml).unwrap();
    let water = Registry::from_toml(&water_source().toml).unwrap();
    writeln!(s, "| Registry | `bbl` canonicalizes to | Dimension | Factor |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for (label, r) in [("oil@1.4", &oil), ("water@2.1", &water)] {
        let u = canonicalize("bbl", r, 1).unwrap();
        writeln!(
            s,
            "| {label} | `{}` | {} | `{}` |",
            u.canonical,
            fmt_dim(&u),
            r.resolve("bbl").unwrap().factor
        )
        .unwrap();
    }
    let of = oil.resolve("bbl").unwrap().factor.to_f64();
    let wf = water.resolve("bbl").unwrap().factor.to_f64();
    writeln!(
        s,
        "\n!!! danger \"The strings are equal and the quantities are not\"\n\
         \x20   Identical canonical form, identical dimension, values differing by \
         **{:.1}%**. §8.3 says *\"identical canonical units → result keeps the \
         unit\"*, so a join across these two tables succeeds and every row is \
         wrong. §8.1 coerces the right operand only *if units differ* — they do \
         not, so nothing is coerced.\n",
        100.0 * (of / wf - 1.0)
    )
    .unwrap();

    // ---- 2. what a naive merge does -------------------------------------
    writeln!(s, "## What a user gets today\n").unwrap();
    writeln!(s, "| Attempt | Result |").unwrap();
    writeln!(s, "|---|---|").unwrap();
    let concat = format!("{}{}", oil_source().toml, water_source().toml);
    let msg = match Registry::from_toml(&concat) {
        Ok(_) => "loads (!)".to_string(),
        Err(e) => format!("`{}` — {}", e.code_str(), e.message()),
    };
    writeln!(s, "| concatenate the two files | {msg} |").unwrap();
    writeln!(
        s,
        "\nA TOML parser error that never names `bbl`, never mentions units, and \
         offers no way forward — against a carefully written message for every \
         *intra*-registry collision. That asymmetry is AMB-058.\n"
    )
    .unwrap();

    // ---- 3. what to rule on ---------------------------------------------
    writeln!(s, "## Step 1 — ask what must be decided\n").unwrap();
    writeln!(
        s,
        "`contested()` answers before anything fails, matching \
         `would_collide()` one level up:\n"
    )
    .unwrap();
    let sources = [oil_source(), water_source()];
    writeln!(s, "| Symbol | Defined differently by |").unwrap();
    writeln!(s, "|---|---|").unwrap();
    for c in contested(&sources).unwrap() {
        writeln!(s, "| `{}` | {} |", c.symbol, c.sources.join(", ")).unwrap();
    }
    writeln!(
        s,
        "\nNote what is **absent**: both registries define `m` identically, and \
         that is not a contest. Demanding a ruling for every shared symbol would \
         make composition unusable.\n"
    )
    .unwrap();

    writeln!(s, "Ruling on nothing is refused, so the union cannot be published unresolved:\n").unwrap();
    match compose("merged", "2026.07", &sources, &[]) {
        Ok(_) => writeln!(s, "!!! success \"composes\"\n").unwrap(),
        Err(e) => writeln!(s, "!!! failure \"`{}`\"\n    {}\n", e.code_str(), e.message()).unwrap(),
    }

    // ---- 4. the ruling ---------------------------------------------------
    writeln!(s, "## Step 2 — rule, with a reason\n").unwrap();
    let reason = "this deployment is upstream oil production, not water management";
    let c = compose(
        "merged",
        "2026.07",
        &sources,
        &[Resolution::new("bbl", "oil", reason)],
    )
    .expect("composes");
    writeln!(
        s,
        "The reason is **required**, exactly as on `prefix_collisions` \
         (AMB-054) — and here it is load-bearing for a second party: the \
         consumer of the published table, who has no other way to learn why \
         `bbl` means what it does.\n"
    )
    .unwrap();
    writeln!(s, "```toml\n{}```\n", c.toml).unwrap();

    let r = c.registry().unwrap();
    writeln!(s, "| Input | Resolves to | Reads as | From |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for q in ["bbl", "acre_ft", "m", "bbl/m^3"] {
        match canonicalize(q, &r, 1) {
            Ok(u) => writeln!(
                s,
                "| `{q}` | `{}` | {} | {} |",
                u.canonical,
                r.describe(&u.canonical).unwrap_or_else(|| "—".into()),
                if c.applied.iter().any(|a| a.symbol == q) {
                    "**ruled**"
                } else if c.agreed.contains(&q.to_string()) {
                    "both, in agreement"
                } else {
                    "one source only"
                }
            )
            .unwrap(),
            Err(e) => writeln!(s, "| `{q}` | **`{}`** | — | — |", e.code_str()).unwrap(),
        }
    }

    // ---- 5. the pin ------------------------------------------------------
    writeln!(s, "\n## Step 3 — the pin makes the reconciliation checkable\n").unwrap();
    writeln!(
        s,
        "The effective registry has no authored file, so its identity is the \
         hash of its bytes. Serialization is deterministic, so a consumer \
         holding the constituents can **recompose and compare** — the \
         reconciliation is a computation, not a claim.\n"
    )
    .unwrap();
    let again = compose(
        "merged",
        "2026.07",
        &sources,
        &[Resolution::new("bbl", "oil", reason)],
    )
    .unwrap();
    let altered = compose(
        "merged",
        "2026.07",
        &sources,
        &[Resolution::new("bbl", "oil", "we guessed")],
    )
    .unwrap();
    writeln!(s, "| | Pin |").unwrap();
    writeln!(s, "|---|---|").unwrap();
    writeln!(s, "| effective registry | `{}` |", c.pin).unwrap();
    writeln!(s, "| recomposed from the same inputs | `{}` |", again.pin).unwrap();
    writeln!(s, "| **same units, different reason** | `{}` |", altered.pin).unwrap();
    for (n, v, h) in &c.inputs {
        writeln!(s, "| constituent `{n}@{v}` | `{h}` |").unwrap();
    }
    writeln!(
        s,
        "\nReproducible: **{}**. And because the reason lives *inside* the hashed \
         artifact, changing the justification changes the pin — so a seal over \
         the pin covers the reasoning transitively. Nobody can quietly rewrite \
         why `bbl` means the oil barrel.\n",
        if c.pin == again.pin { "yes" } else { "NO — this is a bug" }
    )
    .unwrap();

    // ---- 6. embedding ----------------------------------------------------
    writeln!(s, "## Step 4 — how much of it travels\n").unwrap();
    writeln!(
        s,
        "Both embeddings carry the pin, so both **detect** a substituted or \
         drifted registry — which a bare URL cannot do. They differ in \
         *availability*, not integrity.\n"
    )
    .unwrap();
    let full = c.metadata_bytes(Embedding::Full);
    let pin = c.metadata_bytes(Embedding::Pin);
    writeln!(s, "| Mode | Metadata per table | Resolves offline | Survives the source registries disappearing |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    writeln!(s, "| `Full` — embed the effective registry | {full} B | yes | **yes** |").unwrap();
    writeln!(s, "| `Pin` — embed the hash only | {pin} B | no | no |").unwrap();
    writeln!(
        s,
        "\nFor a published dataset with a decade of shelf life, {full} B against a \
         100 MB file is **{:.5}%** — and it is the only form that still resolves \
         when the constituent registries are gone, which for archival data is the \
         *likely* failure, not an exotic one. For a pipeline emitting millions of \
         small files, per-file duplication is the dominant cost and the pin is the \
         right choice: it still cannot silently resolve against the wrong \
         registry, it can only fail to find the right one.\n",
        100.0 * full as f64 / 100e6
    )
    .unwrap();

    // ---- 7. compression --------------------------------------------------
    writeln!(s, "### Does duplication compress away?\n").unwrap();
    writeln!(
        s,
        "The reasonable hope is that a bundle of files with identical embedded \
         registries compresses the copies to nothing. **Measured, that depends \
         entirely on the container** — and the intuitive choice is the one where \
         it fails.\n"
    )
    .unwrap();

    let blob = c.provenance_json(Embedding::Full).into_bytes();
    let n = 200usize;
    let mut bundle: Vec<u8> = Vec::new();
    let mut payload_only: Vec<u8> = Vec::new();
    for i in 0..n {
        let p = pseudo_payload(8 * 1024, 0x9E3779B97F4A7C15u64.wrapping_mul(i as u64 + 1));
        bundle.extend_from_slice(&blob);
        bundle.extend_from_slice(&p);
        payload_only.extend_from_slice(&p);
    }

    writeln!(
        s,
        "{n} files, each carrying the same {} B embedded block plus 8 KB of \
         incompressible column data. The question is what the embedded copies \
         cost *after* compression, isolated by compressing the payload alone:\n",
        blob.len()
    )
    .unwrap();
    writeln!(s, "| Container | Bundle | Payload alone | Registry cost | Per file |").unwrap();
    writeln!(s, "|---|---|---|---|---|").unwrap();

    // The same bundle again with 64 KB payloads: copies now sit further apart
    // than gzip's 32 KB window, which is the mechanism the prose claims.
    let mut wide_bundle: Vec<u8> = Vec::new();
    let mut wide_payload: Vec<u8> = Vec::new();
    for i in 0..n {
        let p = pseudo_payload(64 * 1024, 0xD1B54A32D192ED03u64.wrapping_mul(i as u64 + 1));
        wide_bundle.extend_from_slice(&blob);
        wide_bundle.extend_from_slice(&p);
        wide_payload.extend_from_slice(&p);
    }

    let cases: [(&str, &str, &[&str], bool); 4] = [
        ("solid stream + zstd -19, 8 KB payloads", "zstd", &["-19", "-c", "-q"], false),
        ("solid stream + gzip -9, 8 KB payloads", "gzip", &["-9", "-c"], false),
        ("solid stream + gzip -9, **64 KB** payloads", "gzip", &["-9", "-c"], true),
        ("per-file compression (zip entry, Parquet block)", "", &[], false),
    ];
    for (label, tool, args, wide) in cases {
        let (bun, pay): (&[u8], &[u8]) = if wide {
            (&wide_bundle, &wide_payload)
        } else {
            (&bundle, &payload_only)
        };
        if tool.is_empty() {
            // A zip entry — and a Parquet metadata block — is compressed on its
            // own, so cross-file redundancy is invisible to the codec by
            // construction. Model it by compressing one copy and multiplying.
            let one = compressed_len("gzip", &["-9", "-c"], &blob);
            let pay_one = compressed_len("gzip", &["-9", "-c"], &pseudo_payload(8 * 1024, 7));
            match (one, pay_one) {
                (Some(o), Some(_)) => writeln!(
                    s,
                    "| {label} | — | — | {} KB | **{o} B** |",
                    (o * n) / 1024
                )
                .unwrap(),
                _ => writeln!(s, "| {label} | *tool unavailable* | | | |").unwrap(),
            }
            continue;
        }
        match (compressed_len(tool, args, bun), compressed_len(tool, args, pay)) {
            (Some(b), Some(p)) => writeln!(
                s,
                "| {label} | {} KB | {} KB | {} KB | **{} B** |",
                b / 1024,
                p / 1024,
                b.saturating_sub(p) / 1024,
                b.saturating_sub(p) / n
            )
            .unwrap(),
            _ => writeln!(s, "| {label} | *tool unavailable on this machine* | | | |").unwrap(),
        }
    }

    writeln!(
        s,
        "\nThree different answers to the same question:\n\n\
         - **zstd over a solid stream deduplicates almost perfectly.** Its window \
         is megabytes, so every copy after the first is a back-reference.\n\
         - **gzip deduplicates only while copies stay within its 32 KB window.** \
         The two gzip rows above differ in nothing but payload size, and that \
         alone moves the per-file cost by two orders of magnitude.\n\
         - **Per-entry compression never deduplicates at all.** A `zip` entry — \
         and a Parquet metadata block — is compressed independently, so identical \
         blocks in sibling files are invisible to the codec no matter how large \
         its window.\n\n\
         !!! warning \"The practical consequence\"\n\
         \x20   *\"Zip up the bundle\"* is precisely the case where embedded \
         registries do **not** compress away. `tar` + `zstd` is where they nearly \
         vanish. If the deployment is millions of small files, do not rely on the \
         container — use the pin.\n"
    )
    .unwrap();

    // ---- 7b. the boundary check (AMB-059) --------------------------------
    writeln!(s, "## Reading a table someone else tagged\n").unwrap();
    writeln!(
        s,
        "Composition settles what *this* deployment means. §5.6's boundary check \
         settles what happens when a table arrives tagged against something \
         else — the case that was silently wrong until AMB-059 was ruled.\n"
    )
    .unwrap();
    let oilr = Registry::from_toml(&oil_source().toml).unwrap();
    let waterr = Registry::from_toml(&water_source().toml).unwrap();
    let bump = Registry::from_toml(&format!(
        "{}[unit.acre_ft]\ndimension = \"length\"\nfactor = [616740919, 500000]\n",
        oil_source().toml
    ))
    .unwrap();

    writeln!(s, "| Incoming table | Pins | Symbols in use | Verdict |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for (label, foreign, lpin, fpin, syms) in [
        ("same registry", &oilr, "sha256:aaa", "sha256:aaa", &["bbl", "m"][..]),
        ("oil 1.4 -> oil 1.5 (adds a unit)", &bump, "sha256:v14", "sha256:v15", &["bbl", "m"][..]),
        ("water registry", &waterr, "sha256:aaa", "sha256:bbb", &["bbl"][..]),
        ("water registry, `bbl` unused", &waterr, "sha256:aaa", "sha256:bbb", &["m"][..]),
    ] {
        let v = check_boundary(&oilr, lpin, foreign, fpin, syms);
        let verdict = match v.strict_code() {
            None => format!("✅ {}", v.message()),
            Some(c) => format!("**`{}`** — {}", c.as_str(), v.message()),
        };
        writeln!(
            s,
            "| {label} | {} | `{}` | {verdict} |",
            if lpin == fpin { "equal" } else { "differ" },
            syms.join("`, `")
        )
        .unwrap();
    }
    writeln!(
        s,
        "\nFour properties worth reading off that table.\n\n\
         **Equal pins check nothing.** The single-registry path — almost all \
         traffic — pays one string comparison.\n\n\
         **A version bump that touches nothing in use is free.** This is why the \
         rule compares *symbols* rather than pins: a pin comparison would reject \
         every bump, and bumps are the common case.\n\n\
         **The disagreement names the magnitude.** *Values differ by 33.4%* is \
         actionable; *factors differ* is not.\n\n\
         **Only what the schema uses is checked.** The last row disagrees about \
         `bbl` — but the incoming table does not carry it, so nothing is wrong \
         and nothing is reported.\n"
    )
    .unwrap();
    writeln!(
        s,
        "!!! warning \"Could not check is not checked and agreed\"\n\
         \x20   Under §5.6's **pin** embedding the source registry may be \
         unobtainable. That is a third verdict, never folded into agreement:\n\n\
         \x20   `{}`\n",
        unverifiable("sha256:local", "sha256:foreign").message()
    )
    .unwrap();

    // ---- 8. what the consumer does ---------------------------------------
    writeln!(s, "## What a consumer actually does\n").unwrap();
    writeln!(s, "| Question | What it takes |").unwrap();
    writeln!(s, "|---|---|").unwrap();
    writeln!(s, "| What is this column's unit worth? | one lookup in the effective registry |").unwrap();
    writeln!(
        s,
        "| Why does `bbl` mean *that* here? | `[registry.reconciliation.bbl]` — \"{}\" |",
        c.applied.first().map(|a| a.reason.as_str()).unwrap_or("—")
    )
    .unwrap();
    writeln!(s, "| Am I resolving against the right registry? | `verify_pin(fetched, pin)` |").unwrap();
    writeln!(s, "| Do I trust the inputs? | fetch `composed_from`, recompose, compare pins, check each seal |").unwrap();

    let tampered = c.toml.replace("oil barrel", "oil barrel ");
    writeln!(
        s,
        "\nThe verification is real, not decorative — a single trailing space in \
         a display name is enough:\n\n\
         | Fetched registry | `verify_pin` |\n|---|---|\n\
         | as published | {} |\n| one character changed | {} |\n",
        if verify_pin(&c.toml, &c.pin) { "✅ matches" } else { "❌" },
        if verify_pin(&tampered, &c.pin) { "matches" } else { "❌ **rejected**" }
    )
    .unwrap();

    writeln!(
        s,
        "\n---\n\n!!! note \"Status\"\n\
         \x20   Implemented in `unitarrow_core::compose`, tested, and generated \
         here by running it — but **not yet specified**. §5.6 pins `registry` \
         singular while listing `vocabularies` plural, and the sentence \
         justifying the plural form applies verbatim to registries. AMB-058, \
         AMB-059 and AMB-060 are open and awaiting a ruling.\n"
    )
    .unwrap();

    s
}

