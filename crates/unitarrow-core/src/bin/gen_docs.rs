/// The `ft` case, end to end. Every registry on this page is loaded live, so the
/// verdicts are the implementation's rather than a description of it.
fn page_ambiguity() -> String {
    let mut s = String::new();
    writeln!(s, "# When one spelling means two things\n").unwrap();
    writeln!(
        s,
        "`ft` is *foot*. In a registry that lets `t` (tonne) take SI prefixes, \
         `ft` is also *femto-tonne*. This page works that case through, because \
         it is the clearest example of a rule the rest of the design turns on: \
         **ambiguity is resolved by the registry author, at load — never by the \
         user, at tag time.**\n"
    )
    .unwrap();
    writeln!(
        s,
        "!!! abstract \"The short version\"\n    \
         `ft` almost always means foot. Asking every user to disambiguate a case \
         that essentially never arises would tax the common path to serve the \
         empty one. So the registry decides once, in writing, and users type \
         `ft`.\n"
    )
    .unwrap();

    let base = "[registry]\nschema_version = 1\nname = \"d\"\nversion = \"1\"\n";
    let foot = "[unit.ft]\ndimension = \"length\"\nfactor = [381, 1250]\n\
                display = { long = \"foot\" }\n";
    let tonne = "[unit.t]\ndimension = \"mass\"\nfactor = [1000, 1]\n\
                 prefixes = \"si-engineering\"\ndisplay = { long = \"tonne\", plural = \"tonnes\" }\n";

    // ---- 1. neither reading is contested -------------------------------
    writeln!(s, "## First: most registries never have this problem\n").unwrap();
    writeln!(
        s,
        "The collision needs *both* readings to exist. Declare only one and `ft` \
         is simply unambiguous — no declaration, no ceremony.\n"
    )
    .unwrap();
    writeln!(s, "| Registry contains | `ft` resolves to |").unwrap();
    writeln!(s, "|---|---|").unwrap();
    for (label, src) in [
        ("`ft` (foot), and `t` **not** prefixed", format!("{base}{foot}[unit.t]\ndimension = \"mass\"\nfactor = [1000, 1]\n")),
        ("`t` prefixed, and no `ft` declared", format!("{base}{tonne}")),
    ] {
        let verdict = match Registry::from_toml(&src) {
            Ok(r) => match r.resolve("ft") {
                Some(u) => format!(
                    "`{}` — {} ({})",
                    u.symbol,
                    r.describe("ft").unwrap_or_default(),
                    u.dimension_name
                ),
                None => "*unresolved*".into(),
            },
            Err(e) => format!("`{}`", e.code_str()),
        };
        writeln!(s, "| {label} | {verdict} |").unwrap();
    }

    // ---- 2. the collision, unresolved -----------------------------------
    writeln!(s, "\n## Both readings present: the registry will not load\n").unwrap();
    writeln!(
        s,
        "This is deliberate. A registry that resolves `ft` differently depending \
         on which implementation read it is worse than one that refuses to load, \
         so the ambiguity is caught where it can still be fixed cheaply.\n"
    )
    .unwrap();
    writeln!(s, "```toml\n{base}{foot}{tonne}```\n").unwrap();
    match Registry::from_toml(&format!("{base}{foot}{tonne}")) {
        Ok(_) => writeln!(s, "!!! success \"loads\"\n").unwrap(),
        Err(e) => writeln!(
            s,
            "!!! failure \"`{}`\"\n    {}\n",
            e.code_str(),
            e.message()
        )
        .unwrap(),
    }

    // ---- 3. resolved -----------------------------------------------------
    writeln!(s, "## The author decides, and records why\n").unwrap();
    let decl = "[registry.prefix_collisions]\nft = \"foot is ubiquitous in this domain; femto-tonne is not a real quantity\"\n";
    writeln!(s, "```toml\n{decl}```\n").unwrap();
    let resolved = format!("{base}{decl}{foot}{tonne}");
    let r = Registry::from_toml(&resolved).expect("resolved registry loads");
    writeln!(s, "| Input | Resolves to | Dimension | Reads as |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for q in ["ft", "foot", "t", "tonne", "kt", "Mt", "Gt", "femtotonne", "ft*s^-1"] {
        match canonicalize(q, &r, 1) {
            Ok(u) => writeln!(
                s,
                "| `{q}` | `{}` | {} | {} |",
                u.canonical,
                fmt_dim(&u),
                r.describe(&u.canonical).unwrap_or_else(|| "—".into())
            )
            .unwrap(),
            Err(e) => writeln!(s, "| `{q}` | **`{}`** | — | — |", e.code_str()).unwrap(),
        }
    }

    writeln!(
        s,
        "\nTwo rows are worth pausing on.\n\n\
         **`Gt` still resolves.** That is why narrowing `[unit.t].prefixes` would \
         have been the wrong fix — global emissions are reported in gigatonnes, \
         and dropping the femto end to avoid `ft` would have taken the giga end \
         with it or left the collision in place.\n\n\
         **`femtotonne` does not resolve**, and that is correct rather than a \
         limitation. A prefixed unit's canonical form *is* its symbol (§6.3). \
         Once `ft` belongs to foot, femto-tonne has no canonical spelling left — \
         so a verbose escape hatch would hand back canonical `ft`, meaning foot. \
         Shadowing removes the reading; it does not relocate it.\n"
    )
    .unwrap();

    s.push_str(&section_refused());

    // ---- 4. why not long names ------------------------------------------
    s.push_str(&section_reserved());

    writeln!(s, "## \"Why not just call it `femtotonne` everywhere?\"\n").unwrap();
    writeln!(
        s,
        "A fair question — abbreviations do feel like a display concern. It was \
         measured, and it moves the ambiguity rather than removing it.\n"
    )
    .unwrap();
    writeln!(
        s,
        "The decisive case: **two registries can both spell it `foot`.**\n"
    )
    .unwrap();
    writeln!(s, "| Registry | Long name | Factor | 10 km reads as |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for (label, factor) in [("international", "[381, 1250]"), ("US survey", "[1200, 3937]")] {
        let src = format!(
            "{base}[unit.ft]\ndimension = \"length\"\nfactor = {factor}\n\
             display = {{ long = \"foot\" }}\n"
        );
        let reg = Registry::from_toml(&src).unwrap();
        let f = reg.resolve("ft").unwrap().factor;
        writeln!(
            s,
            "| {label} | foot | `{}` = {:.9} m | {:.2} ft |",
            f,
            f.to_f64(),
            10_000.0 / f.to_f64()
        )
        .unwrap();
    }
    writeln!(
        s,
        "\nBoth are correct. They differ in the eighth digit, which is 2 cm over \
         10 km — and surveying cares. Renaming the canonical form to `foot` \
         changes nothing, because that ambiguity is **across registries**, not \
         within one. Only the registry pin — name, version, content hash (§5.6) \
         — resolves it, and it does so whichever spelling canonical form uses.\n\n\
         Two further reasons, both measurable: most long names are not legal \
         symbols (`megawatt hour`, `degree Celsius`, `British thermal unit \
         (IT)`), so canonical form would need a word-joining rule — the same \
         hazard that makes `m s` an error. And SI *symbols* are language-neutral \
         by design while SI *names* are translated, so long names would make the \
         cross-language equality primitive depend on a spelling choice in one \
         language.\n"
    )
    .unwrap();

    writeln!(s, "## Where each concern is handled\n").unwrap();
    writeln!(s, "| Concern | Layer | Mechanism |").unwrap();
    writeln!(s, "|---|---|---|").unwrap();
    for (concern, layer, how) in [
        ("Two readings of one spelling", "registry, at load", "`prefix_collisions`, or the load fails"),
        ("Same spelling, different registries", "the artifact", "registry pin: name + version + content hash (§5.6)"),
        ("User does not know the symbol", "input", "verbose names — `megawatt`, `kilometer`"),
        ("User typed a display form", "input", "`°C` reports *write `degC`*"),
        ("User wants to check a tag", "output", "reverse lookup — `MW` reads as *megawatt*"),
        ("Reader wants something legible", "display", "registry display forms, not canonical form"),
    ] {
        writeln!(s, "| {concern} | {layer} | {how} |").unwrap();
    }
    writeln!(
        s,
        "\nThe pattern: **every ambiguity is resolved as early as it can be, and \
         by whoever has the context to resolve it.** The registry author knows \
         whether `ft` means foot. The user tagging a column does not, and should \
         never be asked.\n"
    )
    .unwrap();
    s
}

/// The reserved-symbol surface, computed from a registry rather than described.
/// "femto" + `t` reads as "femtot"; the base's long name makes it "femtotonne".
fn prefixed_reading(r: &Registry, risk: &unitarrow_core::CollisionRisk) -> String {
    match r.resolve(&risk.base).and_then(|u| u.display.long.clone()) {
        Some(long) => format!("{}{long}", risk.prefix_long),
        None => format!("{} + `{}`", risk.prefix_long, risk.base),
    }
}

fn section_reserved() -> String {
    let mut s = String::new();
    writeln!(s, "\n## For registry developers: which symbols are taken\n").unwrap();
    writeln!(
        s,
        "The reserved set is **not a fixed list**. It is derived from which units \
         a registry made prefixable, so it differs registry to registry — which \
         is exactly why it needs to be queryable rather than memorised.\n"
    )
    .unwrap();

    let src = "[registry]\nschema_version = 1\nname = \"d\"\nversion = \"1\"\n\
               [dimension.power]\nvector = { mass = 1, length = 2, time = -3 }\n\
               [unit.t]\ndimension = \"mass\"\nfactor = [1000, 1]\n\
               prefixes = \"si-engineering\"\ndisplay = { long = \"tonne\" }\n\
               [unit.W]\ndimension = \"power\"\nfactor = [1, 1]\n\
               prefixes = \"si-engineering\"\ndisplay = { long = \"watt\" }\n";
    let r = Registry::from_toml(src).expect("demo registry loads");

    writeln!(
        s,
        "Two prefixable units — `t` and `W`, each with the engineering set — \
         claim **{} spellings**:\n",
        r.prefix_reserved().len()
    )
    .unwrap();
    writeln!(s, "```text\n{}\n```\n", r.prefix_reserved().join("  ")).unwrap();
    writeln!(
        s,
        "Declaring any of those as a unit is a collision. `ft` is the famous one \
         because *foot* is a real unit people want; most of the rest \
         (`at`, `Gt`, `nW`) nobody would declare, which is why the check is \
         cheap in practice.\n"
    )
    .unwrap();

    writeln!(s, "### Check before you declare\n").unwrap();
    writeln!(
        s,
        "`Registry::would_collide` answers the question proactively, so the \
         answer arrives while you are writing the entry rather than when the \
         load fails:\n"
    )
    .unwrap();
    writeln!(s, "| Symbol you want | Contested by | Verdict |").unwrap();
    writeln!(s, "|---|---|---|").unwrap();
    for candidate in ["ft", "kt", "mW", "mile", "acre", "t", "W", "pW"] {
        match r.would_collide(candidate) {
            Some(risk) => writeln!(
                s,
                "| `{candidate}` | `{}` + `{}` — {} | **contested** |",
                risk.prefix,
                risk.base,
                prefixed_reading(&r, &risk)
            )
            .unwrap(),
            None => writeln!(s, "| `{candidate}` | — | free |").unwrap(),
        }
    }

    writeln!(s, "\n### Review what a registry decided\n").unwrap();
    writeln!(
        s,
        "`Registry::collision_risks` lists every contested spelling and whether \
         the author resolved it — one place to see every judgement call a \
         registry made, which is what a reviewer needs and what a diff will not \
         show:\n"
    )
    .unwrap();
    let contested = "[registry]\nschema_version = 1\nname = \"d\"\nversion = \"1\"\n\
                     [registry.prefix_collisions]\n\
                     ft = \"foot is ubiquitous in this domain; femto-tonne is not a real quantity\"\n\
                     [unit.ft]\ndimension = \"length\"\nfactor = [381, 1250]\n\
                     display = { long = \"foot\" }\n\
                     [unit.t]\ndimension = \"mass\"\nfactor = [1000, 1]\n\
                     prefixes = \"si-engineering\"\ndisplay = { long = \"tonne\" }\n";
    let r2 = Registry::from_toml(contested).expect("loads");
    writeln!(s, "| Spelling | Authored as | Prefixed reading | Why the author chose it |").unwrap();
    writeln!(s, "|---|---|---|---|").unwrap();
    for risk in r2.collision_risks() {
        let reading = prefixed_reading(&r2, &risk);
        writeln!(
            s,
            "| `{}` | {} | {} | {} |",
            risk.symbol,
            risk.authored.as_deref().unwrap_or("—"),
            reading,
            risk.reason.as_deref().unwrap_or("**unresolved**")
        )
        .unwrap();
    }
    writeln!(
        s,
        "\nAn unresolved row cannot exist in a *loaded* registry — that is a load \
         error — so this table always reads as \"here is what the author decided, \
         and why\". The reason is **required**, not optional: the declaration sits \
         in the header, far from the `[unit.ft]` entry it silently affects, so a \
         diff of that entry cannot show the trade-off. Without a stated reason a \
         reviewer has to reconstruct the judgement from two distant places, and a \
         later maintainer has nothing to weigh when the domain changes.\n"
    )
    .unwrap();

    writeln!(s, "### Rules of thumb\n").unwrap();
    for rule in [
        "**Short symbols are the risky ones.** Every collision is prefix + base, \
         so a one- or two-character base makes a two- or three-character \
         contested set. Longer symbols are almost never contested.",
        "**Narrowing the prefix set is usually the wrong fix.** Dropping `femto` \
         to free `ft` also drops the top of the range if the set is symmetric — \
         and `Gt` is how emissions are reported. Resolve the one spelling \
         instead.",
        "**Resolving is not free.** `prefix_collisions` makes the prefixed \
         reading *unavailable*, not merely verbose, because its canonical form \
         was the contested symbol. Do it where the authored unit genuinely \
         matters more, which for `ft` it does.",
        "**A stale entry is an error.** Declaring a symbol with no collision fails \
         the load, so the table cannot rot into a set of claims nobody checks.",
        "**Write the reason for the next maintainer, not the compiler.** \
         \"foot is far more common here than femto-tonne\" survives a domain \
         change legibly; \"collision\" does not. It is the only record of a \
         decision a diff cannot show.",
    ] {
        writeln!(s, "- {rule}").unwrap();
    }
    s.push('\n');
    s
}

fn page_conformance(root: &Path) -> String {
    let mut s = String::new();
    writeln!(s, "# Conformance suite\n").unwrap();
    writeln!(
        s,
        "Spec §11: *\"Every binding runs the full suite. A new binding is \
         conformant when it passes **without modification to the golden \
         files**.\"* The tables below were produced by running this build against \
         those files.\n"
    )
    .unwrap();

    let dir = root.join("conformance/fixtures/parsing");
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();

    let mut total = 0usize;
    let mut passed = 0usize;
    let mut provisional = 0usize;
    let mut rows = String::new();
    let mut failures = Vec::new();
    let mut blockers: BTreeMap<String, usize> = BTreeMap::new();

    for path in &files {
        let doc = json_lite::parse(&std::fs::read_to_string(path).unwrap()).unwrap();
        let reg_name = doc.get("registry").and_then(Json::as_str).unwrap();
        let reg_file = reg_name.split('@').next().unwrap();
        let reg_src =
            std::fs::read_to_string(root.join("conformance/registry").join(format!("{reg_file}.toml")))
                .unwrap();
        let registry = Registry::from_toml(&reg_src).unwrap();

        let cases = doc.get("cases").and_then(Json::as_array).unwrap();
        let mut file_pass = 0usize;
        let mut file_prov = 0usize;
        for case in cases {
            total += 1;
            let id = case.get("id").and_then(Json::as_str).unwrap();
            if case.get("status").and_then(Json::as_str) == Some("provisional") {
                provisional += 1;
                file_prov += 1;
                if let Some(bs) = case.get("blocked_on").and_then(Json::as_array) {
                    for b in bs.iter().filter_map(Json::as_str) {
                        *blockers.entry(b.to_string()).or_insert(0) += 1;
                    }
                }
            }
            if case_passes(case, &registry) {
                passed += 1;
                file_pass += 1;
            } else {
                failures.push(id.to_string());
            }
        }
        writeln!(
            rows,
            "| `{}` | {} | {} | {} | {} |",
            path.file_name().unwrap().to_string_lossy(),
            cases.len(),
            file_pass,
            file_prov,
            doc.get("description").and_then(Json::as_str).unwrap_or("")
        )
        .unwrap();
    }

    if failures.is_empty() {
        writeln!(
            s,
            "!!! success \"{passed} / {total} cases pass\"\n    \
             No fixture was modified. {provisional} of them are `provisional` — \
             their expected values encode a *recommended* resolution to an open \
             register entry rather than ratified spec text.\n"
        )
        .unwrap();
    } else {
        writeln!(
            s,
            "!!! failure \"{} of {total} cases fail\"\n    {}\n",
            failures.len(),
            failures.join(", ")
        )
        .unwrap();
    }

    writeln!(s, "| Fixture | Cases | Pass | Provisional | Covers |").unwrap();
    writeln!(s, "|---|---|---|---|---|").unwrap();
    s.push_str(&rows);

    if !blockers.is_empty() {
        writeln!(s, "\n## What the provisional cases are waiting on\n").unwrap();
        writeln!(s, "| Register entry | Cases blocked |").unwrap();
        writeln!(s, "|---|---|").unwrap();
        for (id, n) in &blockers {
            writeln!(s, "| `{id}` | {n} |").unwrap();
        }
        writeln!(
            s,
            "\nAll M1-scope: the affine compound boundary, delta-unit rules, the \
             exponent-range error code, per-unit quantities, and the reader-mode \
             default. Every M0 canonical-form entry is ruled and applied.\n"
        )
        .unwrap();
    }
    s
}

fn case_passes(case: &Json, registry: &Registry) -> bool {
    let input = case.get("input").unwrap();
    let grammar = case.get("grammar").and_then(Json::as_i64).unwrap_or(1) as u32;
    let expect = case.get("expect").unwrap();
    let decoded: Result<String, unitarrow_core::Error> = match input.get("unit_json") {
        Some(tok) => check_unit_token(tok.as_str().unwrap()).map(str::to_string),
        None => Ok(input.get("unit").and_then(Json::as_str).unwrap().to_string()),
    };
    let result = decoded.and_then(|s| canonicalize(&s, registry, grammar));
    match expect.get("outcome").and_then(Json::as_str) {
        Some("error") => result
            .err()
            .is_some_and(|e| Some(e.code_str()) == expect.get("code").and_then(Json::as_str)),
        Some("ok") => result.is_ok_and(|u| {
            let want: BTreeMap<String, i64> = expect
                .get("dimension")
                .and_then(Json::as_object)
                .map(|o| o.iter().filter_map(|(k, v)| v.as_i64().map(|n| (k.clone(), n))).collect())
                .unwrap_or_default();
            let got: BTreeMap<String, i64> = u
                .dimension
                .sparse()
                .into_iter()
                .map(|(k, v)| (k.to_string(), v as i64))
                .collect();
            Some(u.canonical.as_str()) == expect.get("canonical").and_then(Json::as_str) && got == want
        }),
        _ => false,
    }
}

