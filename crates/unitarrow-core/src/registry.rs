//! Registry loading and load-time validation (spec §7).
//!
//! A **registry** defines measurement itself — dimensions and units. A
//! **vocabulary** defines domain meaning — quantity kinds only (§3, §7.4). One
//! registry is loaded per deployment; many vocabularies may be.
//!
//! Validation is not optional decoration. §7.4 makes federation the normal
//! case, so third-party artifacts reach the resolution path that canonical form
//! and every conversion factor depend on. A *signed* catalog is attributable,
//! not conformant — so these checks run regardless of seal state, and their
//! failures are never phrased as trust failures.



